/** Whether `frame` intersects any active display, in CG global (top-left origin) coordinates —
 *  the space kAXPositionAttribute reports in. A raw fact for TypeScript's decoy judgment. */
bool FrameIntersectsAnyDisplay(CGRect frame) {
  CGDirectDisplayID displays[16];
  uint32_t count = 0;
  if (CGGetActiveDisplayList(16, displays, &count) != kCGErrorSuccess) return true;
  for (uint32_t i = 0; i < count; i += 1) {
    if (CGRectIntersectsRect(CGDisplayBounds(displays[i]), frame)) return true;
  }
  return count == 0;
}

bool IsAttributeSettable(AXUIElementRef element, CFStringRef attribute) {
  Boolean settable = false;
  if (AXUIElementIsAttributeSettable(element, attribute, &settable) != kAXErrorSuccess) return false;
  return settable ? true : false;
}

/**
 * Every attribute the element advertises. This is what lets text capability be *detected* rather
 * than guessed from a list of known roles: an element that carries AXValue and AXSelectedTextRange
 * behaves like a text box no matter what an application chose to call it.
 */
std::vector<std::string> CopyAttributeNames(AXUIElementRef element) {
  std::vector<std::string> names;
  CFArrayRef attributes = NULL;
  if (AXUIElementCopyAttributeNames(element, &attributes) != kAXErrorSuccess) return names;
  if (!attributes) return names;
  CFIndex count = CFArrayGetCount(attributes);
  names.reserve(static_cast<size_t>(count));
  for (CFIndex i = 0; i < count; i += 1) {
    CFTypeRef entry = CFArrayGetValueAtIndex(attributes, i);
    if (entry && CFGetTypeID(entry) == CFStringGetTypeID()) {
      names.push_back(CFStringToStd(static_cast<CFStringRef>(entry)));
    }
  }
  CFRelease(attributes);
  return names;
}

/** Mutable text state, read back immediately after a write so TypeScript can verify it landed. */
struct TextState {
  bool hasValue = false;
  std::string value;
  std::string selectedText;
  bool hasSelection = false;
  long selectionStart = 0;
  long selectionLength = 0;
  long numberOfCharacters = -1;
};

void ReadTextState(AXUIElementRef element, CFIndex valueMaxChars, TextState* state) {
  state->hasValue = CopyAxStringCapped(element, kAXValueAttribute, valueMaxChars, &state->value);
  CopyAxString(element, kAXSelectedTextAttribute, &state->selectedText);
  CFRange range = CFRangeMake(0, 0);
  if (CopyAxRange(element, kAXSelectedTextRangeAttribute, &range)) {
    state->hasSelection = true;
    state->selectionStart = static_cast<long>(range.location);
    state->selectionLength = static_cast<long>(range.length);
  }
  CopyAxLong(element, kAXNumberOfCharactersAttribute, &state->numberOfCharacters);
}

Napi::Object TextStateToObject(Napi::Env env, const TextState& state) {
  Napi::Object object = Napi::Object::New(env);
  object.Set("hasValue", Napi::Boolean::New(env, state.hasValue));
  object.Set("value", Napi::String::New(env, state.value));
  object.Set("selectedText", Napi::String::New(env, state.selectedText));
  if (state.hasSelection) {
    object.Set("selectionStart", Napi::Number::New(env, static_cast<double>(state.selectionStart)));
    object.Set("selectionLength",
               Napi::Number::New(env, static_cast<double>(state.selectionLength)));
  } else {
    object.Set("selectionStart", env.Null());
    object.Set("selectionLength", env.Null());
  }
  object.Set("numberOfCharacters",
             Napi::Number::New(env, static_cast<double>(state.numberOfCharacters)));
  return object;
}

/** Attributes identifying an element well enough to refuse writing into a different one. */
struct ElementIdentity {
  std::string role;
  std::string subrole;
  std::string title;
  std::string description;
  std::string placeholder;
  std::string identifier;
};

void ReadIdentity(AXUIElementRef element, ElementIdentity* identity) {
  CopyAxString(element, kAXRoleAttribute, &identity->role);
  CopyAxString(element, kAXSubroleAttribute, &identity->subrole);
  CopyAxString(element, kAXTitleAttribute, &identity->title);
  CopyAxString(element, kAXDescriptionAttribute, &identity->description);
  CopyAxString(element, CFSTR("AXPlaceholderValue"), &identity->placeholder);
  CopyAxString(element, CFSTR("AXIdentifier"), &identity->identifier);
}

void AssignIdentity(Napi::Object object, const ElementIdentity& identity) {
  Napi::Env env = object.Env();
  object.Set("role", Napi::String::New(env, identity.role));
  object.Set("subrole", Napi::String::New(env, identity.subrole));
  object.Set("title", Napi::String::New(env, identity.title));
  object.Set("description", Napi::String::New(env, identity.description));
  object.Set("placeholder", Napi::String::New(env, identity.placeholder));
  object.Set("identifier", Napi::String::New(env, identity.identifier));
}

/** Applies the messaging timeout that keeps a wedged target app from blocking a libuv worker. */
void ApplyTimeout(AXUIElementRef element, double timeoutMs) {
  AXUIElementSetMessagingTimeout(element, static_cast<float>(timeoutMs / 1000.0));
}

/**
 * The pid owning the frontmost ordinary window, straight from the window server, or -1.
 *
 * Deliberately NOT NSWorkspace's frontmostApplication and NOT the system-wide accessibility
 * element's focused application: both are notification-fed caches that need a serviced run
 * loop, and in a plain Node process (no NSRunLoop) both freeze at their first answer forever,
 * silently — measured, including the AX one. The window list is a fresh window-server round
 * trip on every call. Layer 0 filters to ordinary application windows; the list is ordered
 * front to back, so the first hit is the window under the user's keys. Window OWNERSHIP is
 * plain metadata, readable without the Screen Recording permission that window NAMES need.
 */
pid_t FocusedAppPid() {
  CFArrayRef windows = CGWindowListCopyWindowInfo(
      kCGWindowListOptionOnScreenOnly | kCGWindowListExcludeDesktopElements, kCGNullWindowID);
  if (!windows) return -1;
  pid_t pid = -1;
  CFIndex count = CFArrayGetCount(windows);
  for (CFIndex i = 0; i < count && pid < 0; i += 1) {
    CFDictionaryRef window =
        static_cast<CFDictionaryRef>(CFArrayGetValueAtIndex(windows, i));
    if (!window) continue;
    CFNumberRef layerRef =
        static_cast<CFNumberRef>(CFDictionaryGetValue(window, kCGWindowLayer));
    int layer = -1;
    if (!layerRef || !CFNumberGetValue(layerRef, kCFNumberIntType, &layer) || layer != 0) {
      continue;
    }
    CFNumberRef ownerRef =
        static_cast<CFNumberRef>(CFDictionaryGetValue(window, kCGWindowOwnerPID));
    int owner = -1;
    if (ownerRef && CFNumberGetValue(ownerRef, kCFNumberIntType, &owner)) {
      pid = static_cast<pid_t>(owner);
    }
  }
  CFRelease(windows);
  return pid;
}

/** Copies the focused element of `pid`, with the timeout already applied. Caller CFReleases. */
AXUIElementRef CopyFocusedElement(pid_t pid, double timeoutMs) {
  AXUIElementRef app = AXUIElementCreateApplication(pid);
  if (!app) return NULL;
  ApplyTimeout(app, timeoutMs);
  CFTypeRef focused = NULL;
  AXError error = AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute, &focused);
  CFRelease(app);
  if (error != kAXErrorSuccess || !focused) return NULL;
  if (CFGetTypeID(focused) != AXUIElementGetTypeID()) {
    CFRelease(focused);
    return NULL;
  }
  AXUIElementRef element = static_cast<AXUIElementRef>(focused);
  ApplyTimeout(element, timeoutMs);
  return element;
}

// ── Async workers ───────────────────────────────────────────────────────────

/** Shared promise plumbing: every worker here resolves a JS promise or rejects with an Error. */
class PromiseWorker : public Napi::AsyncWorker {
 public:
  explicit PromiseWorker(Napi::Env env)
      : Napi::AsyncWorker(env), deferred_(Napi::Promise::Deferred::New(env)) {}

  Napi::Promise Promise() { return deferred_.Promise(); }

 protected:
  void OnError(const Napi::Error& error) override { deferred_.Reject(error.Value()); }

  Napi::Promise::Deferred deferred_;
};

class ReadFocusedWorker : public PromiseWorker {
 public:
  ReadFocusedWorker(Napi::Env env, pid_t pid, double timeoutMs, CFIndex valueMaxChars)
      : PromiseWorker(env), pid_(pid), timeoutMs_(timeoutMs), valueMaxChars_(valueMaxChars) {}

  void Execute() override {
    AXUIElementRef element = CopyFocusedElement(pid_, timeoutMs_);
    if (!element) return;

    ReadIdentity(element, &identity_);
    // A password field's text must not reach the JS heap at all. macOS normally withholds it from
    // AXValue, but the classification is cheap here and this is the earliest point it can hold —
    // TypeScript rejecting the element later is a second line, not the first.
    if (identity_.subrole != "AXSecureTextField") {
      ReadTextState(element, valueMaxChars_, &state_);
    }
    attributeNames_ = CopyAttributeNames(element);
    valueSettable_ = IsAttributeSettable(element, kAXValueAttribute);
    selectedTextSettable_ = IsAttributeSettable(element, kAXSelectedTextAttribute);
    enabled_ = CopyAxBool(element, kAXEnabledAttribute, true);
    CGPoint origin = CGPointZero;
    CGSize size = CGSizeZero;
    if (CopyAxPoint(element, kAXPositionAttribute, &origin) &&
        CopyAxSize(element, kAXSizeAttribute, &size)) {
      hasFrame_ = true;
      frame_ = CGRectMake(origin.x, origin.y, size.width, size.height);
      frameOnScreen_ = FrameIntersectsAnyDisplay(frame_);
    }
    token_ = ElementRegistry::Shared().Store(element);
    found_ = true;
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    if (!found_) {
      deferred_.Resolve(env.Null());
      return;
    }
    Napi::Object result = TextStateToObject(env, state_);
    AssignIdentity(result, identity_);
    result.Set("token", Napi::String::New(env, token_));
    result.Set("valueSettable", Napi::Boolean::New(env, valueSettable_));
    result.Set("selectedTextSettable", Napi::Boolean::New(env, selectedTextSettable_));
    result.Set("enabled", Napi::Boolean::New(env, enabled_));
    if (hasFrame_) {
      Napi::Object frame = Napi::Object::New(env);
      frame.Set("x", Napi::Number::New(env, frame_.origin.x));
      frame.Set("y", Napi::Number::New(env, frame_.origin.y));
      frame.Set("width", Napi::Number::New(env, frame_.size.width));
      frame.Set("height", Napi::Number::New(env, frame_.size.height));
      result.Set("frame", frame);
      result.Set("frameOnScreen", Napi::Boolean::New(env, frameOnScreen_));
    } else {
      result.Set("frame", env.Null());
      result.Set("frameOnScreen", Napi::Boolean::New(env, true));
    }
    Napi::Array attributes = Napi::Array::New(env, attributeNames_.size());
    for (size_t i = 0; i < attributeNames_.size(); i += 1) {
      attributes.Set(i, Napi::String::New(env, attributeNames_[i]));
    }
    result.Set("attributeNames", attributes);
    deferred_.Resolve(result);
  }

 private:
  pid_t pid_;
  double timeoutMs_;
  CFIndex valueMaxChars_;
  bool found_ = false;
  std::string token_;
  ElementIdentity identity_;
  TextState state_;
  std::vector<std::string> attributeNames_;
  bool valueSettable_ = false;
  bool selectedTextSettable_ = false;
  bool enabled_ = true;
  bool hasFrame_ = false;
  CGRect frame_ = CGRectZero;
  bool frameOnScreen_ = true;
};

/**
 * Re-reads the identity of the app's currently focused element and reports whether it is the very
 * same element object captured earlier (CFEqual on the AXUIElementRef, which is stronger than any
 * attribute comparison). TypeScript still compares the identity string on top of this.
 */
class VerifyWorker : public PromiseWorker {
 public:
  VerifyWorker(Napi::Env env, std::string token, pid_t pid, double timeoutMs)
      : PromiseWorker(env), token_(std::move(token)), pid_(pid), timeoutMs_(timeoutMs) {}

  void Execute() override {
    AXUIElementRef captured = ElementRegistry::Shared().Copy(token_);
    if (!captured) return;
    AXUIElementRef focused = CopyFocusedElement(pid_, timeoutMs_);
    if (!focused) {
      CFRelease(captured);
      return;
    }
    sameElement_ = CFEqual(captured, focused) ? true : false;
    ReadIdentity(focused, &identity_);
    enabled_ = CopyAxBool(focused, kAXEnabledAttribute, true);
    found_ = true;
    CFRelease(focused);
    CFRelease(captured);
  }

  void OnOK() override {
    Napi::Env env = Env();
    if (!found_) {
      deferred_.Resolve(env.Null());
      return;
    }
    Napi::Object result = Napi::Object::New(env);
    AssignIdentity(result, identity_);
    result.Set("sameElement", Napi::Boolean::New(env, sameElement_));
    result.Set("enabled", Napi::Boolean::New(env, enabled_));
    deferred_.Resolve(result);
  }

 private:
  std::string token_;
  pid_t pid_;
  double timeoutMs_;
  bool found_ = false;
  bool sameElement_ = false;
  bool enabled_ = true;
  ElementIdentity identity_;
};

/**
 * Sets one text attribute and reads the element back in the same trip. The read-back is the only
 * way to tell a real write from the silent no-op many apps return success for.
 */
class SetTextWorker : public PromiseWorker {
 public:
  SetTextWorker(Napi::Env env, std::string token, CFStringRef attribute, std::string text,
                double timeoutMs, CFIndex valueMaxChars)
      : PromiseWorker(env),
        token_(std::move(token)),
        attribute_(attribute),
        text_(std::move(text)),
        timeoutMs_(timeoutMs),
        valueMaxChars_(valueMaxChars) {}

  void Execute() override {
    AXUIElementRef element = ElementRegistry::Shared().Copy(token_);
    if (!element) {
      error_ = "unknown-token";
      return;
    }
    ApplyTimeout(element, timeoutMs_);
    CFStringRef value = CreateCFString(text_);
    if (!value) {
      CFRelease(element);
      error_ = "encoding-failed";
      return;
    }
    AXError result = AXUIElementSetAttributeValue(element, attribute_, value);
    CFRelease(value);
    ok_ = result == kAXErrorSuccess;
    if (!ok_) error_ = "ax-error-" + std::to_string(static_cast<int>(result));
    ReadTextState(element, valueMaxChars_, &after_);
    hasAfter_ = true;
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    Napi::Object result = Napi::Object::New(env);
    result.Set("ok", Napi::Boolean::New(env, ok_));
    result.Set("error", error_.empty() ? env.Null() : Napi::String::New(env, error_).As<Napi::Value>());
    result.Set("after", hasAfter_ ? TextStateToObject(env, after_).As<Napi::Value>() : env.Null());
    deferred_.Resolve(result);
  }

 private:
  std::string token_;
  CFStringRef attribute_;
  std::string text_;
  double timeoutMs_;
  CFIndex valueMaxChars_;
  bool ok_ = false;
  bool hasAfter_ = false;
  std::string error_;
  TextState after_;
};

/**
 * Reads only [range] of the element's text via the parameterized AXStringForRange attribute,
 * falling back to slicing a full value read for views that do not implement it. Either way the
 * caller pays O(range) marshalling, not O(document). Caller CFReleases *out on true.
 */
bool CopyStringForRange(AXUIElementRef element, CFRange range, CFStringRef* out) {
  AXValueRef rangeValue = AXValueCreate(kAXValueTypeCFRange, &range);
  if (rangeValue) {
    CFTypeRef result = NULL;
    AXError err = AXUIElementCopyParameterizedAttributeValue(
        element, kAXStringForRangeParameterizedAttribute, rangeValue, &result);
    CFRelease(rangeValue);
    if (err == kAXErrorSuccess && result) {
      if (CFGetTypeID(result) == CFStringGetTypeID()) {
        *out = static_cast<CFStringRef>(result);
        return true;
      }
      CFRelease(result);
    }
  }
  CFTypeRef value = NULL;
  if (AXUIElementCopyAttributeValue(element, kAXValueAttribute, &value) != kAXErrorSuccess ||
      !value) {
    return false;
  }
  if (CFGetTypeID(value) != CFStringGetTypeID()) {
    CFRelease(value);
    return false;
  }
  CFStringRef whole = static_cast<CFStringRef>(value);
  CFIndex length = CFStringGetLength(whole);
  if (range.location > length || range.location + range.length > length) {
    CFRelease(whole);
    return false;
  }
  CFStringRef slice = CFStringCreateWithSubstring(kCFAllocatorDefault, whole, range);
  CFRelease(whole);
  if (!slice) return false;
  *out = slice;
  return true;
}

/** Whether the element's text over [location, location+expected.size()) equals `expected`. */
bool RegionEquals(AXUIElementRef element, CFIndex location, const std::u16string& expected) {
  if (expected.empty()) return true;
  CFStringRef actual = NULL;
  if (!CopyStringForRange(element,
                          CFRangeMake(location, static_cast<CFIndex>(expected.size())),
                          &actual)) {
    return false;
  }
  CFStringRef wanted = CFStringCreateWithCharacters(
      kCFAllocatorDefault, reinterpret_cast<const UniChar*>(expected.data()),
      static_cast<CFIndex>(expected.size()));
  bool equal = wanted && CFStringCompare(actual, wanted, 0) == kCFCompareEqualTo;
  CFRelease(actual);
  if (wanted) CFRelease(wanted);
  return equal;
}

/**
 * Compare-and-swap on a text region: the streaming hot path, fused into ONE worker trip.
 *
 * Sequence, all against the pinned element without ever crossing back into JavaScript:
 *   1. prove the element is still its application's focused element (CFEqual — by-reference,
 *      stronger than any attribute comparison)
 *   2. compare: the region [regionStart, regionStart+expected.len) must hold exactly `expected`
 *      — a content precondition strictly stronger than an identity re-read, and the reason no
 *      frontmost check appears here: an Accessibility write lands on the element it references,
 *      so unlike the synthetic-event rungs there is no misdirection for a frontmost check to
 *      prevent
 *   3. swap: select the TS-computed edit span inside the region and replace the selection
 *   4. verify the resulting region text, with one blocking settle retry for views that mirror
 *      their text asynchronously
 *   5. park the caret at the TS-chosen position — skipped when the live caret was not where the
 *      last update left it, because then the user moved it and it is not ours to move back
 *
 * Every offset is UTF-16 units on both sides (JavaScript strings and CFRange agree), so values
 * pass through untranslated. The fallback ladder and every retry POLICY stay in TypeScript;
 * this is one atomic primitive, not a strategy.
 */
class CasRangeEditWorker : public PromiseWorker {
 public:
  CasRangeEditWorker(Napi::Env env, std::string token, CFIndex regionStart,
                     std::u16string expected, CFIndex editStart, CFIndex editEnd,
                     std::u16string replacement, CFIndex parkAt, CFIndex expectedCaret,
                     bool preferSplice, double timeoutMs)
      : PromiseWorker(env),
        token_(std::move(token)),
        regionStart_(regionStart),
        expected_(std::move(expected)),
        editStart_(editStart),
        editEnd_(editEnd),
        replacement_(std::move(replacement)),
        parkAt_(parkAt),
        expectedCaret_(expectedCaret),
        preferSplice_(preferSplice),
        timeoutMs_(timeoutMs) {}

  void Execute() override {
    AXUIElementRef element = ElementRegistry::Shared().Copy(token_);
    if (!element) {
      reason_ = "element-gone";
      return;
    }
    ApplyTimeout(element, timeoutMs_);

    pid_t pid = -1;
    if (AXUIElementGetPid(element, &pid) != kAXErrorSuccess) {
      CFRelease(element);
      reason_ = "element-gone";
      return;
    }
    AXUIElementRef focused = CopyFocusedElement(pid, timeoutMs_);
    if (!focused) {
      CFRelease(element);
      reason_ = "element-gone";
      return;
    }
    bool sameElement = CFEqual(element, focused) ? true : false;
    CFRelease(focused);
    if (!sameElement) {
      CFRelease(element);
      reason_ = "element-changed";
      return;
    }

    // The user's caret, before we touch anything: if it is not where the last update parked
    // it, the user moved it and the park below must not fight them.
    bool caretIsOurs = expectedCaret_ < 0;
    CFRange liveSelection = CFRangeMake(0, 0);
    if (CopyAxRange(element, kAXSelectedTextRangeAttribute, &liveSelection)) {
      if (expectedCaret_ >= 0) {
        caretIsOurs = liveSelection.length == 0 && liveSelection.location == expectedCaret_;
      }
    }

    if (!RegionEquals(element, regionStart_, expected_)) {
      CFRelease(element);
      reason_ = "region-mismatch";
      return;
    }

    CFRange editRange =
        CFRangeMake(regionStart_ + editStart_, editEnd_ - editStart_);
    AXValueRef editValue = AXValueCreate(kAXValueTypeCFRange, &editRange);
    if (!editValue) {
      CFRelease(element);
      reason_ = "select-failed";
      return;
    }
    AXError selectError =
        AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute, editValue);
    CFRelease(editValue);
    if (selectError != kAXErrorSuccess) {
      CFRelease(element);
      reason_ = "select-failed";
      return;
    }
    // Placement must be read back on the mirror-settle schedule: Chromium reports the OLD
    // selection in the same trip and lands the new one moments later.
    bool placedOk = false;
    for (int attempt = 0; attempt <= kMirrorSettleSteps && !placedOk; attempt += 1) {
      if (attempt > 0) usleep(kMirrorSettleUs[attempt - 1]);
      CFRange placed = CFRangeMake(-1, -1);
      placedOk = CopyAxRange(element, kAXSelectedTextRangeAttribute, &placed) &&
                 placed.location == editRange.location && placed.length == editRange.length;
    }
    if (!placedOk) {
      CFRelease(element);
      reason_ = "select-failed";
      return;
    }

    // The final region = expected with the edit span replaced, spliced here mechanically from
    // the TS-provided pieces.
    std::u16string finalRegion = expected_.substr(0, static_cast<size_t>(editStart_));
    finalRegion += replacement_;
    finalRegion += expected_.substr(static_cast<size_t>(editEnd_));

    bool landed = false;
    if (!preferSplice_) {
      CFStringRef replacementValue = CFStringCreateWithCharacters(
          kCFAllocatorDefault, reinterpret_cast<const UniChar*>(replacement_.data()),
          static_cast<CFIndex>(replacement_.size()));
      if (!replacementValue) {
        CFRelease(element);
        reason_ = "write-failed";
        return;
      }
      AXError writeError =
          AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute, replacementValue);
      CFRelease(replacementValue);
      // Quick check only — immediate plus one short settle. Exhausting the full schedule here
      // would bill every update in an engine that ignores this attribute for the discovery.
      if (writeError == kAXErrorSuccess) {
        for (int attempt = 0; attempt < 2 && !landed; attempt += 1) {
          if (attempt > 0) usleep(kMirrorSettleUs[0]);
          landed = RegionEquals(element, regionStart_, finalRegion);
        }
      }
      if (landed) via_ = "selected-text";
    }

    if (!landed) {
      // Second swap tactic, same contract: Chromium accepts selection-range and whole-value
      // writes but silently ignores kAXSelectedTextAttribute (measured — reported success,
      // text unchanged). Splice the region into the full value and write THAT. Costs
      // O(document) payload where the first tactic is O(edit), which is why it is the
      // fallback — and why the caller can pass preferSplice once it learns which tactic the
      // target answers to.
      landed = SpliceValueAndVerify(element, finalRegion);
      if (landed) via_ = "value-splice";
    }
    if (!landed) {
      CFRelease(element);
      reason_ = "verify-failed";
      return;
    }

    if (parkAt_ >= 0 && caretIsOurs) {
      CFRange park = CFRangeMake(parkAt_, 0);
      AXValueRef parkValue = AXValueCreate(kAXValueTypeCFRange, &park);
      if (parkValue) {
        AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute, parkValue);
        CFRelease(parkValue);
        parked_ = true;
      }
    }
    ok_ = true;
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    Napi::Object result = Napi::Object::New(env);
    result.Set("ok", Napi::Boolean::New(env, ok_));
    result.Set("reason",
               reason_.empty() ? env.Null() : Napi::String::New(env, reason_).As<Napi::Value>());
    result.Set("parked", Napi::Boolean::New(env, parked_));
    result.Set("via",
               via_.empty() ? env.Null() : Napi::String::New(env, via_).As<Napi::Value>());
    deferred_.Resolve(result);
  }

 private:
  /**
   * Rewrites the whole value with the draft region replaced by `finalRegion`, verifying on the
   * settle schedule. The full value is re-read HERE, in the same worker as the precondition,
   * so text outside the region is the freshest readable state.
   */
  bool SpliceValueAndVerify(AXUIElementRef element, const std::u16string& finalRegion) {
    CFTypeRef current = NULL;
    if (AXUIElementCopyAttributeValue(element, kAXValueAttribute, &current) != kAXErrorSuccess ||
        !current) {
      return false;
    }
    if (CFGetTypeID(current) != CFStringGetTypeID()) {
      CFRelease(current);
      return false;
    }
    CFStringRef value = static_cast<CFStringRef>(current);

    // Rich composers render their placeholder as literal text in the accessibility value while
    // the field is empty. Preserving that as "surrounding text" would MATERIALIZE the
    // placeholder into the document — the app's own input path clears it, a raw value write
    // does not. When the whole value equals the element's declared placeholder, the real
    // content is empty and the splice starts from empty.
    CFTypeRef placeholderRef = NULL;
    bool valueIsPlaceholder = false;
    if (CFStringGetLength(value) > 0 &&
        AXUIElementCopyAttributeValue(element, CFSTR("AXPlaceholderValue"), &placeholderRef) ==
            kAXErrorSuccess &&
        placeholderRef) {
      if (CFGetTypeID(placeholderRef) == CFStringGetTypeID()) {
        valueIsPlaceholder =
            CFStringCompare(value, static_cast<CFStringRef>(placeholderRef), 0) ==
            kCFCompareEqualTo;
      }
      CFRelease(placeholderRef);
    }
    if (valueIsPlaceholder) {
      CFRelease(value);
      // Phantom-relative offsets would splice into text that is not really there; the draft's
      // coordinates are only meaningful against empty content when it starts at zero.
      if (regionStart_ != 0 || !expected_.empty()) return false;
      CFStringRef next = CFStringCreateWithCharacters(
          kCFAllocatorDefault, reinterpret_cast<const UniChar*>(finalRegion.data()),
          static_cast<CFIndex>(finalRegion.size()));
      if (!next) return false;
      AXError wrote = AXUIElementSetAttributeValue(element, kAXValueAttribute, next);
      CFRelease(next);
      if (wrote != kAXErrorSuccess) return false;
      for (int attempt = 0; attempt <= kMirrorSettleSteps; attempt += 1) {
        if (attempt > 0) usleep(kMirrorSettleUs[attempt - 1]);
        if (RegionEquals(element, 0, finalRegion)) return true;
      }
      return false;
    }

    CFIndex length = CFStringGetLength(value);
    CFIndex regionEnd = regionStart_ + static_cast<CFIndex>(expected_.size());
    if (regionStart_ > length || regionEnd > length) {
      CFRelease(value);
      return false;
    }

    std::u16string whole(static_cast<size_t>(length), u'\0');
    CFStringGetCharacters(value, CFRangeMake(0, length),
                          reinterpret_cast<UniChar*>(whole.data()));
    CFRelease(value);
    // The region must still hold what the precondition saw — the splice is positional, and a
    // mid-flight edit would make these offsets someone else's text.
    if (whole.compare(static_cast<size_t>(regionStart_), expected_.size(), expected_) != 0) {
      return false;
    }
    whole.replace(static_cast<size_t>(regionStart_), expected_.size(), finalRegion);

    CFStringRef next = CFStringCreateWithCharacters(
        kCFAllocatorDefault, reinterpret_cast<const UniChar*>(whole.data()),
        static_cast<CFIndex>(whole.size()));
    if (!next) return false;
    AXError wrote = AXUIElementSetAttributeValue(element, kAXValueAttribute, next);
    CFRelease(next);
    if (wrote != kAXErrorSuccess) return false;

    for (int attempt = 0; attempt <= kMirrorSettleSteps; attempt += 1) {
      if (attempt > 0) usleep(kMirrorSettleUs[attempt - 1]);
      if (RegionEquals(element, regionStart_, finalRegion)) return true;
    }
    return false;
  }

  std::string token_;
  CFIndex regionStart_;
  std::u16string expected_;
  CFIndex editStart_;
  CFIndex editEnd_;
  std::u16string replacement_;
  CFIndex parkAt_;
  CFIndex expectedCaret_;
  bool preferSplice_;
  double timeoutMs_;
  bool ok_ = false;
  bool parked_ = false;
  std::string reason_;
  std::string via_;
};

/**
 * Sets the element's selection range — the aiming half of a precise range edit: select
 * [start, start+length), then replace the selection. Reports the range read back in the same
 * trip so TypeScript can tell a landed placement from the silent no-op refusal some views
 * answer with.
 */
class SetSelectionRangeWorker : public PromiseWorker {
 public:
  SetSelectionRangeWorker(Napi::Env env, std::string token, long start, long length,
                          double timeoutMs)
      : PromiseWorker(env),
        token_(std::move(token)),
        start_(start),
        length_(length),
        timeoutMs_(timeoutMs) {}

  void Execute() override {
    AXUIElementRef element = ElementRegistry::Shared().Copy(token_);
    if (!element) {
      error_ = "unknown-token";
      return;
    }
    ApplyTimeout(element, timeoutMs_);
    CFRange range = CFRangeMake(start_, length_);
    AXValueRef value = AXValueCreate(kAXValueTypeCFRange, &range);
    if (!value) {
      CFRelease(element);
      error_ = "encoding-failed";
      return;
    }
    AXError result =
        AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute, value);
    CFRelease(value);
    ok_ = result == kAXErrorSuccess;
    if (!ok_) error_ = "ax-error-" + std::to_string(static_cast<int>(result));
    // Read back on the mirror-settle schedule: Chromium reports the OLD selection in the same
    // trip; without the settle every placement looks failed there.
    CFRange after = CFRangeMake(0, 0);
    for (int attempt = 0; attempt <= kMirrorSettleSteps; attempt += 1) {
      if (attempt > 0) usleep(kMirrorSettleUs[attempt - 1]);
      hasAfter_ = CopyAxRange(element, kAXSelectedTextRangeAttribute, &after);
      if (hasAfter_ && after.location == static_cast<CFIndex>(start_) &&
          after.length == static_cast<CFIndex>(length_)) {
        break;
      }
      if (!ok_) break;
    }
    afterStart_ = static_cast<long>(after.location);
    afterLength_ = static_cast<long>(after.length);
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    Napi::Object result = Napi::Object::New(env);
    result.Set("ok", Napi::Boolean::New(env, ok_));
    result.Set("error",
               error_.empty() ? env.Null() : Napi::String::New(env, error_).As<Napi::Value>());
    if (hasAfter_) {
      result.Set("selectionStart", Napi::Number::New(env, static_cast<double>(afterStart_)));
      result.Set("selectionLength", Napi::Number::New(env, static_cast<double>(afterLength_)));
    } else {
      result.Set("selectionStart", env.Null());
      result.Set("selectionLength", env.Null());
    }
    deferred_.Resolve(result);
  }

 private:
  std::string token_;
  long start_;
  long length_;
  double timeoutMs_;
  bool ok_ = false;
  bool hasAfter_ = false;
  long afterStart_ = 0;
  long afterLength_ = 0;
  std::string error_;
};

