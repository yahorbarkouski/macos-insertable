/**
 * macos-insertable native layer — reads and writes the focused text field of macOS applications.
 *
 * The addon exposes primitives only: it reads raw Accessibility attributes, performs a single
 * requested write, posts synthetic events, and snapshots the pasteboard. Every decision — which
 * delivery rung to take, whether a write actually landed, whether a field is sensitive — lives in
 * TypeScript, where it is unit-testable against a fake binding on any operating system.
 *
 * Threading: Accessibility calls message another process and block, so they run on libuv workers
 * with an explicit messaging timeout. NSWorkspace and NSPasteboard are main-thread APIs and stay
 * synchronous. A pasteboard owner can delay a flavor read, so callers must treat snapshot failure
 * as a normal reason to use a non-paste delivery path.
 *
 * Permission: every AX and CGEvent entry point here requires the macOS Accessibility (TCC) grant.
 * Without it the AX calls return kAXErrorAPIDisabled and the event posts are dropped by the
 * window server. `isAccessibilityTrusted` reports the grant so callers can refuse early.
 */

#import <AppKit/AppKit.h>
#import <ApplicationServices/ApplicationServices.h>
#import <Carbon/Carbon.h>
#import <CoreGraphics/CoreGraphics.h>
#import <IOKit/IOKitLib.h>

// A pasteboard snapshot is held across the paste it protects, which spans several run-loop turns.
// Without ARC the stash keeps raw pointers into an autorelease pool that drains in between, and
// restoring one is a use-after-free that kills the process the moment a paste lands. Host
// processes without a running NSRunLoop never drain, so this cannot be caught by a smoke test —
// only the compiler can enforce it.
#if !__has_feature(objc_arc)
#error "insertable.mm must be compiled with ARC (CLANG_ENABLE_OBJC_ARC in binding.gyp)."
#endif

