/**
 * With NAPI_DISABLE_CPP_EXCEPTIONS a bad `.As<>()` does not throw — it sets a pending JS exception
 * and returns a default-constructed value, and calling further N-API functions in that state is
 * documented as unsafe. A wrong call from TypeScript would therefore take the process down instead
 * of raising a TypeError, so every exported function checks its arguments first.
 */
enum class ArgKind { Number, String };

bool ArgsMatch(const Napi::CallbackInfo& info, std::initializer_list<ArgKind> expected) {
  if (info.Length() < expected.size()) return false;
  size_t index = 0;
  for (ArgKind kind : expected) {
    const Napi::Value value = info[index];
    if (kind == ArgKind::Number && !value.IsNumber()) return false;
    if (kind == ArgKind::String && !value.IsString()) return false;
    index += 1;
  }
  return true;
}

/** Async entry points report a bad call as a rejection rather than a crash. */
Napi::Value RejectBadArgs(Napi::Env env, const char* signature) {
  auto deferred = Napi::Promise::Deferred::New(env);
  deferred.Reject(Napi::TypeError::New(env, signature).Value());
  return deferred.Promise();
}

