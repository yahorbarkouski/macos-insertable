// Virtual keycodes are physical, not character-based, so they hold on any keyboard layout. That
// matters for Command-V specifically: layouts that remap to QWERTY while Command is held resolve
// the *character* "v" to a different physical key.
constexpr CGKeyCode kKeyCodeV = 0x09;
constexpr CGKeyCode kKeyCodeDelete = 0x33;
constexpr CGKeyCode kKeyCodeReturn = 0x24;
constexpr CGKeyCode kKeyCodeCommand = 0x37;
constexpr CGKeyCode kKeyCodeShift = 0x38;

// Passed as the modifier keycode for a keystroke that takes no modifier.
constexpr CGKeyCode kNoModifierKey = 0xFFFF;

// Marker types that ask well-behaved clipboard managers (Maccy, Paste, Raycast, Alfred) not to
// record an item. Text routed through the pasteboard on a caller's behalf is transient by
// definition; delivery must not be what files it into a third-party clipboard history. These are
// conventions published at nspasteboard.org — nothing enforces them, so they reduce the exposure
// rather than removing it.
constexpr const char* kConcealmentTypes[] = {"org.nspasteboard.ConcealedType",
                                             "org.nspasteboard.TransientType",
                                             "org.nspasteboard.AutoGeneratedType"};

// Names the writer, so a clipboard manager honouring the conventions above can attribute the item.
constexpr const char* kPasteboardSourceType = "org.nspasteboard.source";

// CGEventKeyboardSetUnicodeString grows unreliable past roughly this many UTF-16 units per event,
// so typed text is delivered in chunks.
constexpr CFIndex kTypeChunkUnits = 16;

// The typing rung blocks its worker between chunks; a long payload belongs on the paste rung.
constexpr size_t kMaxTypeUnits = 2000;

// Pause between typed chunks. Apps that debounce their own input handling drop characters when
// synthetic events arrive with no gap at all.
constexpr useconds_t kTypeChunkDelayUs = 1200;

// Total bytes a snapshot may hold. A pasteboard over this is not borrowed at all — keeping a
// 50 MB image alive for the length of a paste is not worth it.
constexpr NSUInteger kMaxSnapshotBytes = 16 * 1024 * 1024;

std::string CFStringToStd(CFStringRef value) {
  if (!value) return "";
  CFIndex length = CFStringGetLength(value);
  if (length == 0) return "";
  CFIndex capacity = CFStringGetMaximumSizeForEncoding(length, kCFStringEncodingUTF8) + 1;
  std::vector<char> buffer(static_cast<size_t>(capacity));
  if (!CFStringGetCString(value, buffer.data(), capacity, kCFStringEncodingUTF8)) return "";
  return std::string(buffer.data());
}

CFStringRef CreateCFString(const std::string& value) {
  return CFStringCreateWithBytes(kCFAllocatorDefault,
                                 reinterpret_cast<const UInt8*>(value.data()),
                                 static_cast<CFIndex>(value.size()), kCFStringEncodingUTF8, false);
}

/**
 * Live AXUIElementRefs held across the gap between capture and delivery, addressed by opaque
 * token. Delivery re-finds the element the user was actually focused in rather than trusting
 * whatever holds focus later.
 */
class ElementRegistry {
 public:
  static ElementRegistry& Shared() {
    static ElementRegistry registry;
    return registry;
  }

  std::string Store(AXUIElementRef element) {
    std::lock_guard<std::mutex> guard(mutex_);
    std::string token = "ax-" + std::to_string(++counter_);
    CFRetain(element);
    elements_[token] = element;
    return token;
  }

  /** Returns a retained reference the caller must CFRelease, or NULL when the token is unknown. */
  AXUIElementRef Copy(const std::string& token) {
    std::lock_guard<std::mutex> guard(mutex_);
    auto found = elements_.find(token);
    if (found == elements_.end()) return NULL;
    CFRetain(found->second);
    return found->second;
  }

  void Release(const std::string& token) {
    std::lock_guard<std::mutex> guard(mutex_);
    auto found = elements_.find(token);
    if (found == elements_.end()) return;
    CFRelease(found->second);
    elements_.erase(found);
  }

 private:
  std::mutex mutex_;
  std::map<std::string, AXUIElementRef> elements_;
  uint64_t counter_ = 0;
};

/**
 * Pasteboard contents copied out of the pasteboard so a later clearContents cannot void them.
 *
 * The stash outlives the call that fills it — a snapshot is held across the paste it protects,
 * which spans several run-loop turns. ARC is what makes the map's Objective-C pointers strong;
 * this file must not be compiled without it (see binding.gyp).
 */
class PasteboardStash {
 public:
  static PasteboardStash& Shared() {
    static PasteboardStash stash;
    return stash;
  }

  std::string Store(NSArray<NSPasteboardItem*>* items) {
    std::lock_guard<std::mutex> guard(mutex_);
    std::string token = "pb-" + std::to_string(++counter_);
    items_[token] = items;
    return token;
  }

  NSArray<NSPasteboardItem*>* Take(const std::string& token) {
    std::lock_guard<std::mutex> guard(mutex_);
    auto found = items_.find(token);
    if (found == items_.end()) return nil;
    NSArray<NSPasteboardItem*>* items = found->second;
    items_.erase(found);
    return items;
  }

 private:
  std::mutex mutex_;
  std::map<std::string, NSArray<NSPasteboardItem*>*> items_;
  uint64_t counter_ = 0;
};

// ── Accessibility attribute readers ─────────────────────────────────────────

bool CopyAxString(AXUIElementRef element, CFStringRef attribute, std::string* out) {
  CFTypeRef value = NULL;
  if (AXUIElementCopyAttributeValue(element, attribute, &value) != kAXErrorSuccess) return false;
  if (!value) return false;
  bool ok = false;
  if (CFGetTypeID(value) == CFStringGetTypeID()) {
    *out = CFStringToStd(static_cast<CFStringRef>(value));
    ok = true;
  }
  CFRelease(value);
  return ok;
}

/** Reads a string attribute, truncating to `maxChars` UTF-16 units. */
bool CopyAxStringCapped(AXUIElementRef element, CFStringRef attribute, CFIndex maxChars,
                        std::string* out) {
  CFTypeRef value = NULL;
  if (AXUIElementCopyAttributeValue(element, attribute, &value) != kAXErrorSuccess) return false;
  if (!value) return false;
  bool ok = false;
  if (CFGetTypeID(value) == CFStringGetTypeID()) {
    CFStringRef text = static_cast<CFStringRef>(value);
    CFIndex length = CFStringGetLength(text);
    if (maxChars > 0 && length > maxChars) {
      CFStringRef head = CFStringCreateWithSubstring(kCFAllocatorDefault, text,
                                                     CFRangeMake(0, maxChars));
      // A cut on a UTF-16 boundary can split a surrogate pair; the TypeScript side runs every
      // captured string through a well-formedness pass before it can be serialized.
      *out = CFStringToStd(head);
      if (head) CFRelease(head);
    } else {
      *out = CFStringToStd(text);
    }
    ok = true;
  }
  CFRelease(value);
  return ok;
}

bool CopyAxRange(AXUIElementRef element, CFStringRef attribute, CFRange* out) {
  CFTypeRef value = NULL;
  if (AXUIElementCopyAttributeValue(element, attribute, &value) != kAXErrorSuccess) return false;
  if (!value) return false;
  bool ok = false;
  if (CFGetTypeID(value) == AXValueGetTypeID() &&
      AXValueGetType(static_cast<AXValueRef>(value)) == kAXValueTypeCFRange) {
    ok = AXValueGetValue(static_cast<AXValueRef>(value), kAXValueTypeCFRange, out);
  }
  CFRelease(value);
  return ok;
}

bool CopyAxLong(AXUIElementRef element, CFStringRef attribute, long* out) {
  CFTypeRef value = NULL;
  if (AXUIElementCopyAttributeValue(element, attribute, &value) != kAXErrorSuccess) return false;
  if (!value) return false;
  bool ok = false;
  if (CFGetTypeID(value) == CFNumberGetTypeID()) {
    ok = CFNumberGetValue(static_cast<CFNumberRef>(value), kCFNumberLongType, out);
  }
  CFRelease(value);
  return ok;
}

bool CopyAxBool(AXUIElementRef element, CFStringRef attribute, bool fallback) {
  CFTypeRef value = NULL;
  if (AXUIElementCopyAttributeValue(element, attribute, &value) != kAXErrorSuccess) return fallback;
  if (!value) return fallback;
  bool result = fallback;
  if (CFGetTypeID(value) == CFBooleanGetTypeID()) {
    result = CFBooleanGetValue(static_cast<CFBooleanRef>(value));
  }
  CFRelease(value);
  return result;
}

bool IsAttributeSettable(AXUIElementRef element, CFStringRef attribute) {
  Boolean settable = false;
  if (AXUIElementIsAttributeSettable(element, attribute, &settable) != kAXErrorSuccess) return false;
  return settable ? true : false;
}

/**
 * Every attribute the element advertises. This is what lets text capability be *detected* rather
 * than guessed from a list of known roles: an element that carries AXValue and AXSelectedTextRange
 * behaves like a text box no matter what an application chose to call it.
 */
std::vector<std::string> CopyAttributeNames(AXUIElementRef element) {
  std::vector<std::string> names;
  CFArrayRef attributes = NULL;
  if (AXUIElementCopyAttributeNames(element, &attributes) != kAXErrorSuccess) return names;
  if (!attributes) return names;
  CFIndex count = CFArrayGetCount(attributes);
  names.reserve(static_cast<size_t>(count));
  for (CFIndex i = 0; i < count; i += 1) {
    CFTypeRef entry = CFArrayGetValueAtIndex(attributes, i);
    if (entry && CFGetTypeID(entry) == CFStringGetTypeID()) {
      names.push_back(CFStringToStd(static_cast<CFStringRef>(entry)));
    }
  }
  CFRelease(attributes);
  return names;
}

/** Mutable text state, read back immediately after a write so TypeScript can verify it landed. */
struct TextState {
  bool hasValue = false;
  std::string value;
  std::string selectedText;
  bool hasSelection = false;
  long selectionStart = 0;
  long selectionLength = 0;
  long numberOfCharacters = -1;
};

void ReadTextState(AXUIElementRef element, CFIndex valueMaxChars, TextState* state) {
  state->hasValue = CopyAxStringCapped(element, kAXValueAttribute, valueMaxChars, &state->value);
  CopyAxString(element, kAXSelectedTextAttribute, &state->selectedText);
  CFRange range = CFRangeMake(0, 0);
  if (CopyAxRange(element, kAXSelectedTextRangeAttribute, &range)) {
    state->hasSelection = true;
    state->selectionStart = static_cast<long>(range.location);
    state->selectionLength = static_cast<long>(range.length);
  }
  CopyAxLong(element, kAXNumberOfCharactersAttribute, &state->numberOfCharacters);
}

Napi::Object TextStateToObject(Napi::Env env, const TextState& state) {
  Napi::Object object = Napi::Object::New(env);
  object.Set("hasValue", Napi::Boolean::New(env, state.hasValue));
  object.Set("value", Napi::String::New(env, state.value));
  object.Set("selectedText", Napi::String::New(env, state.selectedText));
  if (state.hasSelection) {
    object.Set("selectionStart", Napi::Number::New(env, static_cast<double>(state.selectionStart)));
    object.Set("selectionLength",
               Napi::Number::New(env, static_cast<double>(state.selectionLength)));
  } else {
    object.Set("selectionStart", env.Null());
    object.Set("selectionLength", env.Null());
  }
  object.Set("numberOfCharacters",
             Napi::Number::New(env, static_cast<double>(state.numberOfCharacters)));
  return object;
}

/** Attributes identifying an element well enough to refuse writing into a different one. */
struct ElementIdentity {
  std::string role;
  std::string subrole;
  std::string title;
  std::string description;
  std::string placeholder;
  std::string identifier;
};

void ReadIdentity(AXUIElementRef element, ElementIdentity* identity) {
  CopyAxString(element, kAXRoleAttribute, &identity->role);
  CopyAxString(element, kAXSubroleAttribute, &identity->subrole);
  CopyAxString(element, kAXTitleAttribute, &identity->title);
  CopyAxString(element, kAXDescriptionAttribute, &identity->description);
  CopyAxString(element, CFSTR("AXPlaceholderValue"), &identity->placeholder);
  CopyAxString(element, CFSTR("AXIdentifier"), &identity->identifier);
}

void AssignIdentity(Napi::Object object, const ElementIdentity& identity) {
  Napi::Env env = object.Env();
  object.Set("role", Napi::String::New(env, identity.role));
  object.Set("subrole", Napi::String::New(env, identity.subrole));
  object.Set("title", Napi::String::New(env, identity.title));
  object.Set("description", Napi::String::New(env, identity.description));
  object.Set("placeholder", Napi::String::New(env, identity.placeholder));
  object.Set("identifier", Napi::String::New(env, identity.identifier));
}

/** Applies the messaging timeout that keeps a wedged target app from blocking a libuv worker. */
void ApplyTimeout(AXUIElementRef element, double timeoutMs) {
  AXUIElementSetMessagingTimeout(element, static_cast<float>(timeoutMs / 1000.0));
}

/**
 * The pid owning the frontmost ordinary window, straight from the window server, or -1.
 *
 * Deliberately NOT NSWorkspace's frontmostApplication and NOT the system-wide accessibility
 * element's focused application: both are notification-fed caches that need a serviced run
 * loop, and in a plain Node process (no NSRunLoop) both freeze at their first answer forever,
 * silently — measured, including the AX one. The window list is a fresh window-server round
 * trip on every call. Layer 0 filters to ordinary application windows; the list is ordered
 * front to back, so the first hit is the window under the user's keys. Window OWNERSHIP is
 * plain metadata, readable without the Screen Recording permission that window NAMES need.
 */
pid_t FocusedAppPid() {
  CFArrayRef windows = CGWindowListCopyWindowInfo(
      kCGWindowListOptionOnScreenOnly | kCGWindowListExcludeDesktopElements, kCGNullWindowID);
  if (!windows) return -1;
  pid_t pid = -1;
  CFIndex count = CFArrayGetCount(windows);
  for (CFIndex i = 0; i < count && pid < 0; i += 1) {
    CFDictionaryRef window =
        static_cast<CFDictionaryRef>(CFArrayGetValueAtIndex(windows, i));
    if (!window) continue;
    CFNumberRef layerRef =
        static_cast<CFNumberRef>(CFDictionaryGetValue(window, kCGWindowLayer));
    int layer = -1;
    if (!layerRef || !CFNumberGetValue(layerRef, kCFNumberIntType, &layer) || layer != 0) {
      continue;
    }
    CFNumberRef ownerRef =
        static_cast<CFNumberRef>(CFDictionaryGetValue(window, kCGWindowOwnerPID));
    int owner = -1;
    if (ownerRef && CFNumberGetValue(ownerRef, kCFNumberIntType, &owner)) {
      pid = static_cast<pid_t>(owner);
    }
  }
  CFRelease(windows);
  return pid;
}

/** Copies the focused element of `pid`, with the timeout already applied. Caller CFReleases. */
AXUIElementRef CopyFocusedElement(pid_t pid, double timeoutMs) {
  AXUIElementRef app = AXUIElementCreateApplication(pid);
  if (!app) return NULL;
  ApplyTimeout(app, timeoutMs);
  CFTypeRef focused = NULL;
  AXError error = AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute, &focused);
  CFRelease(app);
  if (error != kAXErrorSuccess || !focused) return NULL;
  if (CFGetTypeID(focused) != AXUIElementGetTypeID()) {
    CFRelease(focused);
    return NULL;
  }
  AXUIElementRef element = static_cast<AXUIElementRef>(focused);
  ApplyTimeout(element, timeoutMs);
  return element;
}

// ── Async workers ───────────────────────────────────────────────────────────

/** Shared promise plumbing: every worker here resolves a JS promise or rejects with an Error. */
class PromiseWorker : public Napi::AsyncWorker {
 public:
  explicit PromiseWorker(Napi::Env env)
      : Napi::AsyncWorker(env), deferred_(Napi::Promise::Deferred::New(env)) {}

  Napi::Promise Promise() { return deferred_.Promise(); }

 protected:
  void OnError(const Napi::Error& error) override { deferred_.Reject(error.Value()); }

  Napi::Promise::Deferred deferred_;
};

class ReadFocusedWorker : public PromiseWorker {
 public:
  ReadFocusedWorker(Napi::Env env, pid_t pid, double timeoutMs, CFIndex valueMaxChars)
      : PromiseWorker(env), pid_(pid), timeoutMs_(timeoutMs), valueMaxChars_(valueMaxChars) {}

  void Execute() override {
    AXUIElementRef element = CopyFocusedElement(pid_, timeoutMs_);
    if (!element) return;

    ReadIdentity(element, &identity_);
    // A password field's text must not reach the JS heap at all. macOS normally withholds it from
    // AXValue, but the classification is cheap here and this is the earliest point it can hold —
    // TypeScript rejecting the element later is a second line, not the first.
    if (identity_.subrole != "AXSecureTextField") {
      ReadTextState(element, valueMaxChars_, &state_);
    }
    attributeNames_ = CopyAttributeNames(element);
    valueSettable_ = IsAttributeSettable(element, kAXValueAttribute);
    selectedTextSettable_ = IsAttributeSettable(element, kAXSelectedTextAttribute);
    enabled_ = CopyAxBool(element, kAXEnabledAttribute, true);
    token_ = ElementRegistry::Shared().Store(element);
    found_ = true;
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    if (!found_) {
      deferred_.Resolve(env.Null());
      return;
    }
    Napi::Object result = TextStateToObject(env, state_);
    AssignIdentity(result, identity_);
    result.Set("token", Napi::String::New(env, token_));
    result.Set("valueSettable", Napi::Boolean::New(env, valueSettable_));
    result.Set("selectedTextSettable", Napi::Boolean::New(env, selectedTextSettable_));
    result.Set("enabled", Napi::Boolean::New(env, enabled_));
    Napi::Array attributes = Napi::Array::New(env, attributeNames_.size());
    for (size_t i = 0; i < attributeNames_.size(); i += 1) {
      attributes.Set(i, Napi::String::New(env, attributeNames_[i]));
    }
    result.Set("attributeNames", attributes);
    deferred_.Resolve(result);
  }

 private:
  pid_t pid_;
  double timeoutMs_;
  CFIndex valueMaxChars_;
  bool found_ = false;
  std::string token_;
  ElementIdentity identity_;
  TextState state_;
  std::vector<std::string> attributeNames_;
  bool valueSettable_ = false;
  bool selectedTextSettable_ = false;
  bool enabled_ = true;
};

/**
 * Re-reads the identity of the app's currently focused element and reports whether it is the very
 * same element object captured earlier (CFEqual on the AXUIElementRef, which is stronger than any
 * attribute comparison). TypeScript still compares the identity string on top of this.
 */
class VerifyWorker : public PromiseWorker {
 public:
  VerifyWorker(Napi::Env env, std::string token, pid_t pid, double timeoutMs)
      : PromiseWorker(env), token_(std::move(token)), pid_(pid), timeoutMs_(timeoutMs) {}

  void Execute() override {
    AXUIElementRef captured = ElementRegistry::Shared().Copy(token_);
    if (!captured) return;
    AXUIElementRef focused = CopyFocusedElement(pid_, timeoutMs_);
    if (!focused) {
      CFRelease(captured);
      return;
    }
    sameElement_ = CFEqual(captured, focused) ? true : false;
    ReadIdentity(focused, &identity_);
    enabled_ = CopyAxBool(focused, kAXEnabledAttribute, true);
    found_ = true;
    CFRelease(focused);
    CFRelease(captured);
  }

  void OnOK() override {
    Napi::Env env = Env();
    if (!found_) {
      deferred_.Resolve(env.Null());
      return;
    }
    Napi::Object result = Napi::Object::New(env);
    AssignIdentity(result, identity_);
    result.Set("sameElement", Napi::Boolean::New(env, sameElement_));
    result.Set("enabled", Napi::Boolean::New(env, enabled_));
    deferred_.Resolve(result);
  }

 private:
  std::string token_;
  pid_t pid_;
  double timeoutMs_;
  bool found_ = false;
  bool sameElement_ = false;
  bool enabled_ = true;
  ElementIdentity identity_;
};

/**
 * Sets one text attribute and reads the element back in the same trip. The read-back is the only
 * way to tell a real write from the silent no-op many apps return success for.
 */
class SetTextWorker : public PromiseWorker {
 public:
  SetTextWorker(Napi::Env env, std::string token, CFStringRef attribute, std::string text,
                double timeoutMs, CFIndex valueMaxChars)
      : PromiseWorker(env),
        token_(std::move(token)),
        attribute_(attribute),
        text_(std::move(text)),
        timeoutMs_(timeoutMs),
        valueMaxChars_(valueMaxChars) {}

  void Execute() override {
    AXUIElementRef element = ElementRegistry::Shared().Copy(token_);
    if (!element) {
      error_ = "unknown-token";
      return;
    }
    ApplyTimeout(element, timeoutMs_);
    CFStringRef value = CreateCFString(text_);
    if (!value) {
      CFRelease(element);
      error_ = "encoding-failed";
      return;
    }
    AXError result = AXUIElementSetAttributeValue(element, attribute_, value);
    CFRelease(value);
    ok_ = result == kAXErrorSuccess;
    if (!ok_) error_ = "ax-error-" + std::to_string(static_cast<int>(result));
    ReadTextState(element, valueMaxChars_, &after_);
    hasAfter_ = true;
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    Napi::Object result = Napi::Object::New(env);
    result.Set("ok", Napi::Boolean::New(env, ok_));
    result.Set("error", error_.empty() ? env.Null() : Napi::String::New(env, error_).As<Napi::Value>());
    result.Set("after", hasAfter_ ? TextStateToObject(env, after_).As<Napi::Value>() : env.Null());
    deferred_.Resolve(result);
  }

 private:
  std::string token_;
  CFStringRef attribute_;
  std::string text_;
  double timeoutMs_;
  CFIndex valueMaxChars_;
  bool ok_ = false;
  bool hasAfter_ = false;
  std::string error_;
  TextState after_;
};

/**
 * Sets the element's selection range — the aiming half of a precise range edit: select
 * [start, start+length), then replace the selection. Reports the range read back in the same
 * trip so TypeScript can tell a landed placement from the silent no-op refusal some views
 * answer with.
 */
class SetSelectionRangeWorker : public PromiseWorker {
 public:
  SetSelectionRangeWorker(Napi::Env env, std::string token, long start, long length,
                          double timeoutMs)
      : PromiseWorker(env),
        token_(std::move(token)),
        start_(start),
        length_(length),
        timeoutMs_(timeoutMs) {}

  void Execute() override {
    AXUIElementRef element = ElementRegistry::Shared().Copy(token_);
    if (!element) {
      error_ = "unknown-token";
      return;
    }
    ApplyTimeout(element, timeoutMs_);
    CFRange range = CFRangeMake(start_, length_);
    AXValueRef value = AXValueCreate(kAXValueTypeCFRange, &range);
    if (!value) {
      CFRelease(element);
      error_ = "encoding-failed";
      return;
    }
    AXError result =
        AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute, value);
    CFRelease(value);
    ok_ = result == kAXErrorSuccess;
    if (!ok_) error_ = "ax-error-" + std::to_string(static_cast<int>(result));
    CFRange after = CFRangeMake(0, 0);
    hasAfter_ = CopyAxRange(element, kAXSelectedTextRangeAttribute, &after);
    afterStart_ = static_cast<long>(after.location);
    afterLength_ = static_cast<long>(after.length);
    CFRelease(element);
  }

  void OnOK() override {
    Napi::Env env = Env();
    Napi::Object result = Napi::Object::New(env);
    result.Set("ok", Napi::Boolean::New(env, ok_));
    result.Set("error",
               error_.empty() ? env.Null() : Napi::String::New(env, error_).As<Napi::Value>());
    if (hasAfter_) {
      result.Set("selectionStart", Napi::Number::New(env, static_cast<double>(afterStart_)));
      result.Set("selectionLength", Napi::Number::New(env, static_cast<double>(afterLength_)));
    } else {
      result.Set("selectionStart", env.Null());
      result.Set("selectionLength", env.Null());
    }
    deferred_.Resolve(result);
  }

 private:
  std::string token_;
  long start_;
  long length_;
  double timeoutMs_;
  bool ok_ = false;
  bool hasAfter_ = false;
  long afterStart_ = 0;
  long afterLength_ = 0;
  std::string error_;
};

/**
 * Asks an application to build the accessibility tree it otherwise builds only once it detects
 * assistive technology.
 *
 * Chromium — and so every Electron application — reports no focused element at all until then.
 * `AXManualAccessibility` is the opt-in Chromium added for exactly this. `AXEnhancedUserInterface`
 * would also work and is deliberately not used: it additionally moves and resizes windows out
 * from under third-party window managers.
 *
 * Diagnostic use only. Measured across real Electron applications, the attribute is accepted but
 * does not surface fields that were hidden — treat a positive result as an invitation to
 * re-measure, not as coverage.
 */
class PrimeAccessibilityWorker : public PromiseWorker {
 public:
  PrimeAccessibilityWorker(Napi::Env env, pid_t pid, double timeoutMs)
      : PromiseWorker(env), pid_(pid), timeoutMs_(timeoutMs) {}

  void Execute() override {
    AXUIElementRef app = AXUIElementCreateApplication(pid_);
    if (!app) return;
    ApplyTimeout(app, timeoutMs_);
    ok_ = AXUIElementSetAttributeValue(app, CFSTR("AXManualAccessibility"), kCFBooleanTrue) ==
          kAXErrorSuccess;
    CFRelease(app);
  }

  void OnOK() override { deferred_.Resolve(Napi::Boolean::New(Env(), ok_)); }

 private:
  pid_t pid_;
  double timeoutMs_;
  bool ok_ = false;
};

